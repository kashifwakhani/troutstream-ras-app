// Helper to construct realistic water readings
function createWaterReading(
  id: string,
  tankId: string | undefined,
  timeStr: string,
  tempC: number,
  doMgL: number,
  ph: number,
  tanMgL: number,
  no2MgL: number,
  no3MgL: number,
  alkMgL: number,
  co2MgL: number,
  operator: string,
  notes?: string
): WaterQualityReading {
  const nh3 = calculateUnionizedAmmonia(tanMgL, ph, tempC);
  const evalResult = evaluateWaterQuality(
    { temperatureC: tempC, dissolvedOxygenMgL: doMgL, ph, tanMgL, unionizedAmmoniaMgL: nh3, nitriteMgL: no2MgL, co2MgL, alkalinityMgL: alkMgL },
    defaultThresholds
  );

  return {
    id,
    farmId: 'farm-alpine-1',
    tankId,
    waterLoopId: 'loop-alpha',
    timestamp: timeStr,
    temperatureC: tempC,
    dissolvedOxygenMgL: doMgL,
    ph,
    tanMgL,
    unionizedAmmoniaMgL: nh3,
    nitriteMgL: no2MgL,
    nitrateMgL: no3MgL,
    alkalinityMgL: alkMgL,
    co2MgL,
    flowRateM3H: 85,
    waterLevelPct: 98,
    operator,
    notes,
    status: evalResult.status,
    alerts: evalResult.alerts,
  };
}

